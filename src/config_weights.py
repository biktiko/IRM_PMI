def get_canonical_weights(phase: Any, substage: str) -> pd.DataFrame:
    """
    Returns pre-calibrated canonical weights DataFrame for the given phase and substage.
    Supports phase as int (1, 2, 3) or str ('1', '2', '3', 'Phase 1', etc.).
    Returns empty DataFrame if not defined.
    """
    ph_int = None
    try:
        if isinstance(phase, int):
            ph_int = phase
        else:
            ph_s = str(phase).upper().replace("PHASE", "").replace("ՓՈՒԼ", "").strip()
            ph_int = int(ph_s)
    except Exception:
        ph_int = None

    phase_data = WEIGHTS_DATA.get(ph_int, {}) if ph_int is not None else {}
    rows = phase_data.get(substage, [])
    if not rows:
        return pd.DataFrame(columns=[
            "scenario", "section", "question_key", "qkey_norm",
            "weight_in_section", "weight_in_scenario"
        ])
    df = pd.DataFrame(rows)
    df["scenario"] = df["scenario"].astype(str).str.strip()
    df["qkey_norm"] = df["qkey_norm"].astype(str).str.strip()
    return df
